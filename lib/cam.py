"""
Simple 2D CAM toolpath generator for build123d parts.
Generates Grbl-compatible G-code for 2D contour milling.
"""

from typing import List, Tuple, Optional, Dict, Any
from dataclasses import dataclass, field
from enum import Enum
from build123d import Part, Axis, Vector
import math

try:
    from shapely.geometry import Polygon, LinearRing
    from shapely.ops import unary_union
    SHAPELY_AVAILABLE = True
except ImportError:
    SHAPELY_AVAILABLE = False


class OperationType(Enum):
    """Types of machining operations"""
    DRILL = "drill"
    CONTOUR = "contour"
    POCKET = "pocket"
    PROFILE = "profile"


@dataclass
class DrillPoint:
    """Single drill location"""
    x: float
    y: float
    depth: float
    diameter: float = 0  # Optional, for visualization


@dataclass
class Operation:
    """Single machining operation with its own tool and parameters"""
    op_type: OperationType
    name: str
    tool_diameter: float
    spindle_rpm: int
    feed_rate: float
    plunge_rate: float

    # Operation-specific data
    contours: List[List[Tuple[float, float]]] = field(default_factory=list)  # For contour/profile ops
    drill_points: List[DrillPoint] = field(default_factory=list)  # For drill ops

    # Cutting parameters
    depth_of_cut: float = 3.0
    total_depth: float = 12.0
    stepover: float = 0.4

    # Safety
    safe_height: float = 5.0
    retract_height: float = 2.0

    # Drill-specific
    peck_depth: float = 3.0  # Depth per peck when drilling
    dwell_time: float = 0.5  # Dwell at bottom of hole (seconds)

    # Contour-specific
    offset_direction: str = "outside"  # "outside", "inside", "on"
    add_tabs: bool = False
    tab_width: float = 5.0
    tab_height: float = 2.0
    num_tabs: int = 3


@dataclass
class ToolpathConfig:
    """Configuration for toolpath generation"""

    # Tool parameters
    tool_diameter: float  # mm
    spindle_rpm: int
    feed_rate: float  # mm/min
    plunge_rate: float  # mm/min

    # Cutting parameters
    depth_of_cut: float  # mm (per pass)
    total_depth: float  # mm
    stepover: float = 0.4  # fraction of tool diameter for stepover

    # Safety
    safe_height: float = 5.0  # mm above part
    retract_height: float = 2.0  # mm above part for rapid moves

    # Tabs (to hold part in place)
    add_tabs: bool = True
    tab_width: float = 5.0  # mm
    tab_height: float = 2.0  # mm (how much material to leave)
    num_tabs: int = 3

    # Toolpath origin positioning
    zero_to_lower_left: bool = True  # Move toolpath origin to lower-left corner of part
    origin_x: float = 0.0  # mm - X coordinate for toolpath origin
    origin_y: float = 0.0  # mm - Y coordinate for toolpath origin


@dataclass
class Tab:
    """Holding tab definition"""
    start_distance: float  # Distance along edge where tab starts
    width: float  # Width of tab


class GCodeGenerator:
    """Generate Grbl G-code from toolpaths"""

    def __init__(self, config: ToolpathConfig) -> None:
        self.config: ToolpathConfig = config
        self.lines: List[str] = []

    def header(self) -> None:
        """G-code header"""
        safe_z = self.config.total_depth + self.config.safe_height
        self.lines.append("%")
        self.lines.append("(Generated by CNC Toolpath Generator)")
        self.lines.append("(Units: mm)")
        self.lines.append("G21 (Metric)")
        self.lines.append("G90 (Absolute positioning)")
        self.lines.append("G17 (XY plane)")
        self.lines.append(f"M3 S{self.config.spindle_rpm} (Spindle on)")
        self.lines.append("G4 P2 (Pause 2 seconds for spindle)")
        self.lines.append(f"G0 Z{safe_z:.3f} (Rapid to safe height)")

    def footer(self) -> None:
        """G-code footer"""
        safe_z = self.config.total_depth + self.config.safe_height
        self.lines.append(f"G0 Z{safe_z:.3f} (Retract)")
        self.lines.append("M5 (Spindle off)")
        self.lines.append("G0 X0 Y0 (Return to origin)")
        self.lines.append("M2 (Program end)")
        self.lines.append("%")

    def rapid_move(self, x: float, y: float, z: Optional[float] = None) -> None:
        """Rapid positioning"""
        if z is not None:
            self.lines.append(f"G0 X{x:.3f} Y{y:.3f} Z{z:.3f}")
        else:
            self.lines.append(f"G0 X{x:.3f} Y{y:.3f}")

    def feed_move(self, x: float, y: float, z: Optional[float] = None) -> None:
        """Linear move at feed rate"""
        if z is not None:
            self.lines.append(f"G1 X{x:.3f} Y{y:.3f} Z{z:.3f} F{self.config.feed_rate:.0f}")
        else:
            self.lines.append(f"G1 X{x:.3f} Y{y:.3f} F{self.config.feed_rate:.0f}")

    def plunge(self, z: float) -> None:
        """Plunge at plunge rate"""
        self.lines.append(f"G1 Z{z:.3f} F{self.config.plunge_rate:.0f}")

    def arc_move(self, x: float, y: float, i: float, j: float, clockwise: bool = True) -> None:
        """Arc move (G2/G3)"""
        cmd = "G2" if clockwise else "G3"
        self.lines.append(f"{cmd} X{x:.3f} Y{y:.3f} I{i:.3f} J{j:.3f} F{self.config.feed_rate:.0f}")

    def comment(self, text: str) -> None:
        """Add comment"""
        self.lines.append(f"({text})")

    def get_gcode(self) -> str:
        """Get complete G-code as string"""
        return "\n".join(self.lines)


def extract_drill_points(part: Part, min_diameter: float = 0.5, max_diameter: float = 20.0) -> List[DrillPoint]:
    """
    Extract circular holes from a part as drill points.
    Looks for circular edges/faces that represent holes.

    Args:
        part: build123d Part
        min_diameter: Minimum hole diameter to consider (mm)
        max_diameter: Maximum hole diameter to consider (mm)

    Returns:
        List of DrillPoint objects
    """
    drill_points = []

    # Get the top face
    top_face = part.faces().sort_by(Axis.Z)[-1]

    # Look for circular inner wires (holes)
    for inner_wire in top_face.inner_wires():
        edges = inner_wire.edges()

        # Check if this is a circular hole (single circular edge)
        if len(edges) == 1:
            edge = edges[0]

            # Check if it's circular/arc
            try:
                # Get edge center and radius
                if hasattr(edge, 'radius'):
                    radius = edge.radius()
                    diameter = radius * 2

                    # Filter by diameter
                    if min_diameter <= diameter <= max_diameter:
                        center = edge.center()
                        drill_points.append(DrillPoint(
                            x=center.X,
                            y=center.Y,
                            depth=part.bounding_box().size.Z,  # Full thickness
                            diameter=diameter
                        ))
            except:
                pass  # Not a circular edge

    return drill_points


def extract_contours(part: Part) -> List[List[Tuple[float, float]]]:
    """
    Extract 2D contours from a part by projecting top face edges to XY plane.
    Returns list of contours (closed loops of XY points).
    """
    contours = []

    # Get the top face
    top_face = part.faces().sort_by(Axis.Z)[-1]

    # Get outer wire (contour)
    outer_wire = top_face.outer_wire()

    # Convert wire to list of points
    points = []
    for edge in outer_wire.edges():
        # Sample points along edge - increased from 20 to 100 for smoother curves
        samples = 100  # Number of points to sample per edge
        for i in range(samples):
            t = i / samples
            pos = edge.position_at(t)
            points.append((pos.X, pos.Y))

    if points:
        contours.append(points)

    # Get inner wires (holes)
    for inner_wire in top_face.inner_wires():
        points = []
        for edge in inner_wire.edges():
            samples = 100
            for i in range(samples):
                t = i / samples
                pos = edge.position_at(t)
                points.append((pos.X, pos.Y))
        if points:
            contours.append(points)

    return contours


def calculate_tab_positions(contour_length: float, num_tabs: int) -> List[float]:
    """Calculate evenly spaced tab positions along contour"""
    if num_tabs == 0:
        return []

    positions = []
    spacing = contour_length / num_tabs

    for i in range(num_tabs):
        positions.append(i * spacing + spacing / 2)

    return positions


def calculate_contour_bounds(contours: List[List[Tuple[float, float]]]) -> Tuple[float, float, float, float]:
    """
    Calculate bounding box of all contours.
    Returns (min_x, min_y, max_x, max_y)
    """
    if not contours or not any(contours):
        return (0, 0, 0, 0)

    all_points = [point for contour in contours for point in contour]

    min_x = min(x for x, y in all_points)
    min_y = min(y for x, y in all_points)
    max_x = max(x for x, y in all_points)
    max_y = max(y for x, y in all_points)

    return (min_x, min_y, max_x, max_y)


def offset_contours(contours: List[List[Tuple[float, float]]], offset_x: float, offset_y: float) -> List[List[Tuple[float, float]]]:
    """
    Offset all contour points by given X and Y amounts.
    """
    return [
        [(x + offset_x, y + offset_y) for x, y in contour]
        for contour in contours
    ]


def offset_contour_by_tool_radius_shapely(contour: List[Tuple[float, float]], offset_distance: float, tool_diameter: float = 0) -> List[Tuple[float, float]]:
    """
    Offset a closed contour using shapely's robust buffer operation.
    Positive offset moves outward, negative moves inward.

    Args:
        contour: List of (x, y) points forming a closed loop
        offset_distance: Distance to offset (positive = outward, negative = inward)
        tool_diameter: Tool diameter for filtering unmachable features (optional)

    Returns:
        New contour with points offset by the specified distance
    """
    if not SHAPELY_AVAILABLE:
        # Fall back to simple algorithm if shapely not available
        return offset_contour_by_tool_radius_simple(contour, offset_distance)

    if len(contour) < 3:
        return contour

    try:
        # Create a polygon from the contour
        poly = Polygon(contour)

        # Use buffer to offset
        # join_style='mitre' for sharp corners, but with a limit to prevent extreme extensions
        buffered = poly.buffer(offset_distance, join_style='mitre', mitre_limit=2.0)

        # If buffered geometry is too small or empty, skip it
        if buffered.is_empty or buffered.area < 1.0:  # Skip very small features
            print(f"Warning: Offset created very small geometry (area: {buffered.area:.2f}), skipping")
            return []

        # Simplify the geometry to remove details smaller than tool can reach
        # Use tool diameter as tolerance - removes features smaller than the tool
        if tool_diameter > 0:
            tolerance = tool_diameter * 0.1  # 10% of tool diameter
            buffered = buffered.simplify(tolerance, preserve_topology=True)

        # Get coordinates from the buffered polygon
        if hasattr(buffered, 'exterior'):
            # Single polygon result
            coords = list(buffered.exterior.coords[:-1])  # Exclude duplicate closing point
        else:
            # MultiPolygon or other - use largest polygon
            if hasattr(buffered, 'geoms'):
                # Filter out very small polygons (smaller than tool can cut)
                min_area = (tool_diameter ** 2) if tool_diameter > 0 else 1.0
                valid_geoms = [g for g in buffered.geoms if g.area >= min_area]

                if not valid_geoms:
                    print(f"Warning: All offset geometries too small, skipping")
                    return []

                largest = max(valid_geoms, key=lambda p: p.area)
                coords = list(largest.exterior.coords[:-1])
            else:
                return contour

        return coords

    except Exception as e:
        print(f"Warning: Shapely offset failed ({e}), using simple algorithm")
        return offset_contour_by_tool_radius_simple(contour, offset_distance)


def offset_contour_by_tool_radius_simple(contour: List[Tuple[float, float]], offset_distance: float) -> List[Tuple[float, float]]:
    """
    Offset a closed contour perpendicular to its edges by a given distance.
    Positive offset moves outward (for outside cuts), negative moves inward (for inside cuts).

    Args:
        contour: List of (x, y) points forming a closed loop
        offset_distance: Distance to offset (positive = outward, negative = inward)

    Returns:
        New contour with points offset by the specified distance
    """
    if len(contour) < 3:
        return contour  # Not enough points to form a proper contour

    offset_points = []
    n = len(contour)

    for i in range(n):
        # Get current point and its neighbors
        prev_point = contour[(i - 1) % n]
        curr_point = contour[i]
        next_point = contour[(i + 1) % n]

        # Calculate vectors for the two adjacent edges
        # Edge from previous to current
        v1_x = curr_point[0] - prev_point[0]
        v1_y = curr_point[1] - prev_point[1]
        v1_len = math.sqrt(v1_x**2 + v1_y**2)

        # Edge from current to next
        v2_x = next_point[0] - curr_point[0]
        v2_y = next_point[1] - curr_point[1]
        v2_len = math.sqrt(v2_x**2 + v2_y**2)

        # Skip if edges are degenerate
        if v1_len < 1e-6 or v2_len < 1e-6:
            offset_points.append(curr_point)
            continue

        # Normalize edge vectors
        v1_x /= v1_len
        v1_y /= v1_len
        v2_x /= v2_len
        v2_y /= v2_len

        # Calculate perpendicular normals (rotate 90° clockwise for outward direction)
        # For a vector (x, y), rotating clockwise gives (y, -x)
        n1_x = v1_y
        n1_y = -v1_x
        n2_x = v2_y
        n2_y = -v2_x

        # Average the two normals to get the offset direction at this vertex
        avg_normal_x = (n1_x + n2_x) / 2
        avg_normal_y = (n1_y + n2_y) / 2
        avg_len = math.sqrt(avg_normal_x**2 + avg_normal_y**2)

        if avg_len < 1e-6:
            # Normals cancel out (180° corner), use perpendicular to first edge
            avg_normal_x = n1_x
            avg_normal_y = n1_y
            avg_len = 1.0

        # Normalize average normal
        avg_normal_x /= avg_len
        avg_normal_y /= avg_len

        # Calculate the angle between the two edges to determine offset scaling
        # At sharp corners, we need to extend the offset more
        dot_product = v1_x * v2_x + v1_y * v2_y
        dot_product = max(-1.0, min(1.0, dot_product))  # Clamp to valid range
        angle = math.acos(dot_product)

        # Scale offset by 1/sin(angle/2) to maintain consistent distance from original edge
        # This prevents gaps at sharp corners
        if abs(angle) > 1e-6 and abs(angle - math.pi) > 1e-6:
            scale = 1.0 / math.sin(angle / 2)
            # Limit scaling to prevent extreme offsets at very sharp angles
            scale = min(scale, 5.0)
        else:
            scale = 1.0

        # Apply offset
        offset_x = curr_point[0] + avg_normal_x * offset_distance * scale
        offset_y = curr_point[1] + avg_normal_y * offset_distance * scale

        offset_points.append((offset_x, offset_y))

    return offset_points


def generate_drill_toolpath(operation: Operation) -> str:
    """
    Generate G-code for drilling operations with peck drilling.

    Args:
        operation: Operation object with drill points and parameters

    Returns:
        G-code string
    """
    if not operation.drill_points:
        return ""

    # Create minimal config for GCodeGenerator
    class DrillConfig:
        def __init__(self, op: Operation):
            self.spindle_rpm = op.spindle_rpm
            self.feed_rate = op.feed_rate
            self.plunge_rate = op.plunge_rate
            self.total_depth = op.total_depth
            self.safe_height = op.safe_height
            self.retract_height = op.retract_height

    gcode = GCodeGenerator(DrillConfig(operation))
    gcode.header()

    gcode.comment(f"Drilling operation: {operation.name}")
    gcode.comment(f"Tool: {operation.tool_diameter}mm drill")
    gcode.comment(f"Total holes: {len(operation.drill_points)}")
    gcode.comment(f"Peck depth: {operation.peck_depth}mm")

    # Drill each hole
    for i, drill_point in enumerate(operation.drill_points):
        gcode.comment(f"Hole {i+1}/{len(operation.drill_points)}")

        # Rapid to hole location at safe height
        safe_z = operation.total_depth + operation.safe_height
        gcode.rapid_move(drill_point.x, drill_point.y, safe_z)

        # Rapid down to retract height
        retract_z = operation.total_depth + operation.retract_height
        gcode.rapid_move(drill_point.x, drill_point.y, retract_z)

        # Peck drill to final depth
        current_depth = operation.total_depth  # Start at top surface
        target_depth = operation.total_depth - drill_point.depth

        while current_depth > target_depth:
            # Calculate next peck depth
            next_depth = max(current_depth - operation.peck_depth, target_depth)

            # Plunge to depth
            gcode.plunge(next_depth)

            # Check if we've reached final depth
            if next_depth == target_depth:
                # Dwell at bottom
                if operation.dwell_time > 0:
                    gcode.lines.append(f"G4 P{operation.dwell_time:.1f} (Dwell {operation.dwell_time}s)")
                break

            # Retract to clear chips
            gcode.lines.append(f"G0 Z{retract_z:.3f} (Retract to clear chips)")

            # Rapid back down close to current depth
            gcode.lines.append(f"G0 Z{next_depth + 1.0:.3f} (Rapid to resume depth)")

            current_depth = next_depth

        # Retract to safe height
        gcode.rapid_move(drill_point.x, drill_point.y, safe_z)

    gcode.footer()
    return gcode.get_gcode()


def generate_contour_toolpath(
    part: Part,
    config: ToolpathConfig,
    offset_direction: str = "outside"  # "outside", "inside", or "on"
) -> str:
    """
    Generate 2D contour toolpath for a part.

    Args:
        part: build123d Part to generate toolpath for
        config: Toolpath configuration
        offset_direction: Tool offset direction relative to contour

    Returns:
        G-code string
    """
    gcode = GCodeGenerator(config)
    gcode.header()

    # Extract contours from part
    contours = extract_contours(part)

    if not contours:
        gcode.comment("WARNING: No contours found!")
        gcode.footer()
        return gcode.get_gcode()

    # Calculate original bounding box
    min_x, min_y, max_x, max_y = calculate_contour_bounds(contours)
    gcode.comment(f"Part bounds: X({min_x:.3f} to {max_x:.3f}), Y({min_y:.3f} to {max_y:.3f})")

    # Offset contours to position toolpath origin at lower-left corner
    if config.zero_to_lower_left:
        # Calculate offset to move lower-left corner to (origin_x, origin_y)
        offset_x = config.origin_x - min_x
        offset_y = config.origin_y - min_y
        contours = offset_contours(contours, offset_x, offset_y)
        gcode.comment(f"Toolpath origin moved to lower-left corner at ({config.origin_x:.3f}, {config.origin_y:.3f})")
        gcode.comment(f"Offset applied: X{offset_x:+.3f}, Y{offset_y:+.3f}")

    # Calculate tool offset based on direction
    if offset_direction == "outside":
        offset = config.tool_diameter / 2
    elif offset_direction == "inside":
        offset = -config.tool_diameter / 2
    else:  # "on"
        offset = 0

    # Apply tool radius compensation to all contours
    if offset != 0:
        gcode.comment(f"Applying tool radius compensation: {offset:+.3f}mm ({offset_direction})")
        offset_contours_list = []
        for contour in contours:
            offset_contour = offset_contour_by_tool_radius_shapely(
                contour,
                offset,
                tool_diameter=config.tool_diameter
            )
            # Only include non-empty contours (skip features too small for tool)
            if offset_contour:
                offset_contours_list.append(offset_contour)
        contours = offset_contours_list

        if not contours:
            gcode.comment("WARNING: All contours too small for tool diameter, no toolpath generated")
            gcode.footer()
            return gcode.get_gcode()

    # Calculate number of depth passes
    num_passes = math.ceil(config.total_depth / config.depth_of_cut)

    gcode.comment(f"Contour toolpath - {num_passes} depth passes")
    gcode.comment(f"Tool: {config.tool_diameter}mm, Offset: {offset_direction}")

    # Process each contour
    for contour_idx, contour in enumerate(contours):
        gcode.comment(f"Contour {contour_idx + 1}")

        # Calculate contour length for tab placement
        contour_length = sum(
            math.sqrt((contour[i+1][0] - contour[i][0])**2 +
                     (contour[i+1][1] - contour[i][1])**2)
            for i in range(len(contour) - 1)
        )

        # Calculate tab positions
        tab_positions = []
        if config.add_tabs:
            tab_positions = calculate_tab_positions(contour_length, config.num_tabs)

        # Depth passes
        for pass_num in range(num_passes):
            # Calculate depth for this pass (cutting down from top surface)
            cut_depth = min((pass_num + 1) * config.depth_of_cut, config.total_depth)
            depth = config.total_depth - cut_depth

            gcode.comment(f"Pass {pass_num + 1}/{num_passes}, Z: {depth:.3f}mm (cut depth: {cut_depth:.3f}mm)")

            # Move to start point (above part)
            start_x, start_y = contour[0]
            gcode.rapid_move(start_x, start_y, config.total_depth + config.retract_height)

            # Plunge to depth
            gcode.plunge(depth)

            # Cut around contour
            current_distance = 0
            for i in range(1, len(contour)):
                x, y = contour[i]
                prev_x, prev_y = contour[i - 1]

                # Calculate distance along edge
                edge_length = math.sqrt((x - prev_x)**2 + (y - prev_y)**2)

                # Check if we're in a tab zone (only on final pass)
                in_tab = False
                if config.add_tabs and pass_num == num_passes - 1:
                    for tab_pos in tab_positions:
                        if tab_pos - config.tab_width/2 <= current_distance <= tab_pos + config.tab_width/2:
                            in_tab = True
                            break

                # Move to point (raising for tabs)
                if in_tab:
                    # Raise to tab height
                    tab_depth = depth + config.tab_height
                    gcode.feed_move(x, y, tab_depth)
                else:
                    gcode.feed_move(x, y)

                current_distance += edge_length

            # Return to start to close loop
            gcode.feed_move(contour[0][0], contour[0][1])

            # Retract
            gcode.rapid_move(contour[0][0], contour[0][1], config.total_depth + config.retract_height)

    gcode.footer()
    return gcode.get_gcode()


def generate_operation_toolpath(operation: Operation, contours: Optional[List[List[Tuple[float, float]]]] = None) -> str:
    """
    Generate toolpath for a single operation.

    Args:
        operation: Operation definition
        contours: Optional contours for contour/profile operations

    Returns:
        G-code string
    """
    if operation.op_type == OperationType.DRILL:
        return generate_drill_toolpath(operation)

    elif operation.op_type in (OperationType.CONTOUR, OperationType.PROFILE):
        # Use contours from operation or provided contours
        if contours:
            operation.contours = contours

        if not operation.contours:
            return ""

        # Create config from operation
        config = ToolpathConfig(
            tool_diameter=operation.tool_diameter,
            spindle_rpm=operation.spindle_rpm,
            feed_rate=operation.feed_rate,
            plunge_rate=operation.plunge_rate,
            depth_of_cut=operation.depth_of_cut,
            total_depth=operation.total_depth,
            stepover=operation.stepover,
            safe_height=operation.safe_height,
            retract_height=operation.retract_height,
            add_tabs=operation.add_tabs,
            tab_width=operation.tab_width,
            tab_height=operation.tab_height,
            num_tabs=operation.num_tabs,
            zero_to_lower_left=False,  # Assume contours already positioned
            origin_x=0.0,
            origin_y=0.0,
        )

        # Generate contour toolpath (modified to work with pre-extracted contours)
        return generate_contour_toolpath_from_contours(
            contours=operation.contours,
            config=config,
            offset_direction=operation.offset_direction
        )

    return ""


def generate_contour_toolpath_from_contours(
    contours: List[List[Tuple[float, float]]],
    config: ToolpathConfig,
    offset_direction: str = "outside"
) -> str:
    """
    Generate contour toolpath from pre-extracted contours.
    This is similar to generate_contour_toolpath but works with contours directly.
    """
    gcode = GCodeGenerator(config)
    gcode.header()

    if not contours:
        gcode.comment("WARNING: No contours provided!")
        gcode.footer()
        return gcode.get_gcode()

    # Calculate tool offset based on direction
    if offset_direction == "outside":
        offset = config.tool_diameter / 2
    elif offset_direction == "inside":
        offset = -config.tool_diameter / 2
    else:  # "on"
        offset = 0

    # Apply tool radius compensation to all contours
    if offset != 0:
        gcode.comment(f"Applying tool radius compensation: {offset:+.3f}mm ({offset_direction})")
        offset_contours_list = []
        for contour in contours:
            offset_contour = offset_contour_by_tool_radius_shapely(
                contour,
                offset,
                tool_diameter=config.tool_diameter
            )
            # Only include non-empty contours (skip features too small for tool)
            if offset_contour:
                offset_contours_list.append(offset_contour)
        contours = offset_contours_list

        if not contours:
            gcode.comment("WARNING: All contours too small for tool diameter, no toolpath generated")
            gcode.footer()
            return gcode.get_gcode()

    # Calculate number of depth passes
    num_passes = math.ceil(config.total_depth / config.depth_of_cut)

    gcode.comment(f"Contour toolpath - {num_passes} depth passes")
    gcode.comment(f"Tool: {config.tool_diameter}mm, Offset: {offset_direction}")

    # Process each contour (same logic as before)
    for contour_idx, contour in enumerate(contours):
        gcode.comment(f"Contour {contour_idx + 1}")

        # Calculate contour length for tab placement
        contour_length = sum(
            math.sqrt((contour[i+1][0] - contour[i][0])**2 +
                     (contour[i+1][1] - contour[i][1])**2)
            for i in range(len(contour) - 1)
        )

        # Calculate tab positions
        tab_positions = []
        if config.add_tabs:
            tab_positions = calculate_tab_positions(contour_length, config.num_tabs)

        # Depth passes
        for pass_num in range(num_passes):
            # Calculate depth for this pass (cutting down from top surface)
            cut_depth = min((pass_num + 1) * config.depth_of_cut, config.total_depth)
            depth = config.total_depth - cut_depth

            gcode.comment(f"Pass {pass_num + 1}/{num_passes}, Z: {depth:.3f}mm (cut depth: {cut_depth:.3f}mm)")

            # Move to start point (above part)
            start_x, start_y = contour[0]
            gcode.rapid_move(start_x, start_y, config.total_depth + config.retract_height)

            # Plunge to depth
            gcode.plunge(depth)

            # Cut around contour
            current_distance = 0
            for i in range(1, len(contour)):
                x, y = contour[i]
                prev_x, prev_y = contour[i - 1]

                # Calculate distance along edge
                edge_length = math.sqrt((x - prev_x)**2 + (y - prev_y)**2)

                # Check if we're in a tab zone (only on final pass)
                in_tab = False
                if config.add_tabs and pass_num == num_passes - 1:
                    for tab_pos in tab_positions:
                        if tab_pos - config.tab_width/2 <= current_distance <= tab_pos + config.tab_width/2:
                            in_tab = True
                            break

                # Move to point (raising for tabs)
                if in_tab:
                    # Raise to tab height
                    tab_depth = depth + config.tab_height
                    gcode.feed_move(x, y, tab_depth)
                else:
                    gcode.feed_move(x, y)

                current_distance += edge_length

            # Return to start to close loop
            gcode.feed_move(contour[0][0], contour[0][1])

            # Retract
            gcode.rapid_move(contour[0][0], contour[0][1], config.total_depth + config.retract_height)

    gcode.footer()
    return gcode.get_gcode()


def generate_sequenced_operations(operations: List[Operation]) -> Dict[str, Any]:
    """
    Generate toolpaths for a sequence of operations.

    Args:
        operations: List of Operation objects in execution order

    Returns:
        Dictionary with operation data and combined G-code
    """
    all_gcode_parts = []
    operation_metadata = []

    for i, operation in enumerate(operations):
        print(f"Generating operation {i+1}/{len(operations)}: {operation.name}")

        # Generate toolpath for this operation
        gcode = generate_operation_toolpath(operation)

        if gcode:
            all_gcode_parts.append(f"\n(--- Operation {i+1}: {operation.name} ---)\n")
            all_gcode_parts.append(gcode)

            # Store metadata
            operation_metadata.append({
                'index': i,
                'name': operation.name,
                'type': operation.op_type.value,
                'tool_diameter': operation.tool_diameter,
                'spindle_rpm': operation.spindle_rpm,
                'feed_rate': operation.feed_rate,
                'plunge_rate': operation.plunge_rate,
            })

    # Combine all G-code
    combined_gcode = "\n".join(all_gcode_parts)

    return {
        'gcode': combined_gcode,
        'operations': operation_metadata,
        'total_operations': len(operations),
    }


def generate_gcode_for_part(
    part: Part,
    tool_diameter: float = 6.35,  # 1/4"
    material_thickness: float = 12.0,
    spindle_rpm: int = 18000,
    feed_rate: float = 1500,
    depth_of_cut: float = 3.0,
    zero_to_lower_left: bool = True,
    origin_x: float = 0.0,
    origin_y: float = 0.0,
    output_file: Optional[str] = None
) -> str:
    """
    Simple wrapper to generate G-code for a part with sensible defaults.

    Args:
        part: build123d Part
        tool_diameter: Tool diameter in mm
        material_thickness: Material thickness (total cutting depth)
        spindle_rpm: Spindle speed
        feed_rate: Cutting feed rate
        depth_of_cut: Depth per pass in mm
        zero_to_lower_left: Move toolpath origin to lower-left corner
        origin_x: X coordinate for toolpath origin (mm)
        origin_y: Y coordinate for toolpath origin (mm)
        output_file: Optional file path to write G-code

    Returns:
        G-code string
    """
    config = ToolpathConfig(
        tool_diameter=tool_diameter,
        spindle_rpm=spindle_rpm,
        feed_rate=feed_rate,
        plunge_rate=feed_rate / 2,
        depth_of_cut=depth_of_cut,
        total_depth=material_thickness,
        add_tabs=True,
        num_tabs=3,
        zero_to_lower_left=zero_to_lower_left,
        origin_x=origin_x,
        origin_y=origin_y,
    )

    gcode = generate_contour_toolpath(part, config, offset_direction="outside")

    if output_file:
        with open(output_file, 'w') as f:
            f.write(gcode)
        print(f"G-code written to: {output_file}")

    return gcode


